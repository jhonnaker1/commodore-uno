FIRST, LAST, ROWS = 32, 126, 9


def glyph(ch):
    art = LOWER.get(ch) or CAPS.get(ch)
    if art is None:
        return [0] * ROWS
    rows = art.split("|")
    rows += ["....."] * (ROWS - len(rows))
    return [sum(0x80 >> i for i, c in enumerate(r) if c == "#") for r in rows]


def main(out):
    lines = [
        "/* GENERATED by tools/mkfont.py -- edit the ASCII art there. */",
        "#define FONT_FIRST %d" % FIRST,
        "#define FONT_LAST %d" % LAST,
        "#define FONT_ROWS %d" % ROWS,
        "static const unsigned char font5x9[%d][%d] = {" % (LAST - FIRST + 1, ROWS),
    ]
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        name = {" ": "space", "\\": "backslash", "*": "star"}.get(ch, ch)
        lines.append("    {%s}, /* %s */" % (",".join("0x%02X" % b for b in glyph(ch)), name))
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
